def transform(ans, opener, closer):
    m = re.search(r'\*\*(.+?)\*\*', ans)
    if not m:
        return ans  # 不应发生
    bold = ans[m.start():m.end()]      # 含 ** 的加粗结论
    rest = ans[m.end():].lstrip()
    new = bold + " " + opener + " " + rest
    if closer:
        new = new.rstrip() + "\n\n" + closer
    return new


def main():
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    faq = data["faq"]
    assert len(faq) == len(OPENERS) == len(CLOSERS), (
        f"条目数不匹配: faq={len(faq)} openers={len(OPENERS)} closers={len(CLOSERS)}")
    changed = 0
    for i, entry in enumerate(faq):
        old = entry.get("answer_zh", "")
        new = transform(old, OPENERS[i], CLOSERS[i])
        if new != old:
            entry["answer_zh"] = new
            changed += 1
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"已改写 {changed}/{len(faq)} 条回答；文件: {PATH}")


if __name__ == "__main__":
    main()
